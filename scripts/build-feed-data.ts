#!/usr/bin/env bun
/**
 * build-feed-data.ts — extracts the leads into JSON for the Pages Functions.
 *
 * The browser data files are IIFEs that assign onto `window`, and the Workers
 * runtime forbids dynamic evaluation, so the feed and the social-card
 * middleware cannot read them directly. This runs them here, at build time,
 * where a sandbox is allowed, and writes the one thing those functions need.
 *
 * Only the lead per issue is extracted — not the whole paper — so the copy in
 * functions/lib stays small. It is emitted as ESM rather than JSON because a
 * JSON import needs an import attribute that Node and the Workers bundler
 * disagree about; a module is the same everywhere. `--check` fails if it has
 * drifted from data/formats.js, which is what the test suite calls.
 */

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createContext, runInContext } from 'node:vm';

const ROOT = join(import.meta.dirname ?? __dirname, '..');
const OUT = join(ROOT, 'functions', 'lib', 'leads.mjs');

export function extractLeads(): { headline: string; deck: string }[] {
    const sandbox: { window: Record<string, unknown> } = { window: {} };
    createContext(sandbox);
    runInContext(
        readFileSync(join(ROOT, 'data', 'formats.js'), 'utf8'),
        sandbox,
    );
    const data = (
        sandbox.window as { Neckass?: { data?: { LEADS?: unknown } } }
    )?.Neckass?.data;
    const leads = data?.LEADS;
    if (!Array.isArray(leads) || !leads.length) {
        throw new Error('No LEADS found in data/formats.js');
    }
    return leads.map((lead: { headline: string; deck: string }) => ({
        headline: lead.headline,
        deck: lead.deck,
    }));
}

const leads = extractLeads();
const serialized = `${[
    '// Generated by scripts/build-feed-data.ts from data/formats.js.',
    '// Do not edit by hand; run `bun run feed:build`.',
    `export default ${JSON.stringify(leads, null, 4)};`,
].join('\n')}\n`;

if (process.argv.includes('--check')) {
    // Compare against what the module actually exports, so biome owns the
    // file's formatting and this script owns only its content.
    let current: unknown = null;
    try {
        current = (await import(OUT)).default;
    } catch {
        /* missing or unparseable counts as drift */
    }
    if (JSON.stringify(current) !== JSON.stringify(leads)) {
        console.error(
            'functions/lib/leads.mjs is out of date with data/formats.js.\n' +
                'Run `bun run feed:build`.',
        );
        process.exit(1);
    }
    console.log('✅ functions/lib/leads.mjs matches data/formats.js');
} else {
    writeFileSync(OUT, serialized);
    try {
        execSync(`npx biome format --write ${OUT}`, {
            cwd: ROOT,
            stdio: 'ignore',
        });
    } catch {
        /* formatting is a nicety, not a requirement */
    }
    console.log(`✅ wrote ${OUT}`);
}
